CREATE EXTENSION IF NOT EXISTS "uuid-ossp";


-- =============================================================
-- ENUMS
-- =============================================================

CREATE TYPE hunt_status AS ENUM ('draft', 'active', 'ended');
CREATE TYPE submission_status AS ENUM ('pending', 'approved', 'rejected', 'failed');
CREATE TYPE ai_suggested_status AS ENUM ('approved', 'rejected');


-- =============================================================
-- TABLES
-- =============================================================

-- hunt
-- Only one row should have status = 'active' at any time.
-- Enforced via a partial unique index below.
CREATE TABLE hunt (
  id          uuid PRIMARY KEY DEFAULT uuid_generate_v4(),
  title       text NOT NULL,
  status      hunt_status NOT NULL DEFAULT 'draft',
  created_at  timestamptz NOT NULL DEFAULT now(),
  started_at  timestamptz,
  ended_at    timestamptz
);

-- Enforce only one active hunt at a time
CREATE UNIQUE INDEX one_active_hunt
  ON hunt (status)
  WHERE status = 'active';


-- clue
-- unlocked_by_clue_id = NULL means the clue is free-hanging (visible from the start).
-- When set, the clue only unlocks after the referenced clue has been submitted by the team.
-- This supports both sequential chains and always-on clues within the same hunt.
CREATE TABLE clue (
  id                   uuid PRIMARY KEY DEFAULT uuid_generate_v4(),
  hunt_id              uuid NOT NULL REFERENCES hunt (id) ON DELETE CASCADE,
  unlocked_by_clue_id  uuid REFERENCES clue (id) ON DELETE SET NULL,
  body                 text NOT NULL,
  hint                 text,
  location_name        text,
  points_value         int NOT NULL DEFAULT 10
);

CREATE INDEX clue_hunt_id_idx ON clue (hunt_id);
CREATE INDEX clue_unlocked_by_idx ON clue (unlocked_by_clue_id);


-- team
-- name is nullable — set by the first player to join, changeable anytime after.
-- pin is the team credential, generated by admin and shared manually.
-- No Supabase Auth involved for players — sessions are signed cookies.
CREATE TABLE team (
  id           uuid PRIMARY KEY DEFAULT uuid_generate_v4(),
  hunt_id      uuid NOT NULL REFERENCES hunt (id) ON DELETE CASCADE,
  name         text,                -- null until first player sets it
  pin          text NOT NULL,       -- admin-generated, shared manually
  total_score  int NOT NULL DEFAULT 0,

  UNIQUE (hunt_id, pin)
);

CREATE INDEX team_hunt_id_idx ON team (hunt_id);
CREATE INDEX team_pin_idx ON team (pin);


-- player
-- A new row is created on every join, including rejoins.
-- No uniqueness constraints — player identity within a team is not tracked.
-- team_id + name are display only. player_id is stored in the session cookie.
CREATE TABLE player (
  id          uuid PRIMARY KEY DEFAULT uuid_generate_v4(),
  team_id     uuid NOT NULL REFERENCES team (id) ON DELETE CASCADE,
  name        text NOT NULL,
  joined_at   timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX player_team_id_idx ON player (team_id);


-- submission
CREATE TABLE submission (
  id              uuid PRIMARY KEY DEFAULT uuid_generate_v4(),
  team_id         uuid NOT NULL REFERENCES team (id) ON DELETE CASCADE,
  clue_id         uuid NOT NULL REFERENCES clue (id) ON DELETE CASCADE,
  player_id       uuid NOT NULL REFERENCES player (id) ON DELETE CASCADE,
  photo_url       text NOT NULL,
  submitted_at    timestamptz NOT NULL DEFAULT now(),
  reviewed_at     timestamptz,
  status          submission_status NOT NULL DEFAULT 'pending',
  points_awarded  int NOT NULL DEFAULT 0,

  -- One submission per clue per team, enforced at DB level
  UNIQUE (team_id, clue_id)
);

CREATE INDEX submission_team_id_idx ON submission (team_id);
CREATE INDEX submission_status_idx ON submission (status);


-- announcement
CREATE TABLE announcement (
  id          uuid PRIMARY KEY DEFAULT uuid_generate_v4(),
  hunt_id     uuid NOT NULL REFERENCES hunt (id) ON DELETE CASCADE,
  body        text NOT NULL,
  created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX announcement_hunt_id_idx ON announcement (hunt_id);


-- ai_review (Phase 5 — table created now, stays empty until then)
CREATE TABLE ai_review (
  id                uuid PRIMARY KEY DEFAULT uuid_generate_v4(),
  submission_id     uuid NOT NULL REFERENCES submission (id) ON DELETE CASCADE,
  model             text NOT NULL,
  confidence        float NOT NULL CHECK (confidence >= 0 AND confidence <= 1),
  suggested_status  ai_suggested_status NOT NULL,
  reviewed_at       timestamptz NOT NULL DEFAULT now(),

  UNIQUE (submission_id)
);


